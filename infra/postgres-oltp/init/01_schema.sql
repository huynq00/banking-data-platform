-- =============================================================
-- Core Banking (OLTP) schema
-- Runs automatically on the FIRST start of an empty volume.
-- =============================================================

-- -------------------------------------------------------------
-- Keep updated_at current on every UPDATE (needed for auditing,
-- and useful as a fallback for incremental extraction)
-- -------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- -------------------------------------------------------------
-- branches: bank branches (Berka "district")
-- -------------------------------------------------------------
CREATE TABLE branches (
    branch_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code  VARCHAR(10)  NOT NULL UNIQUE,
    name         VARCHAR(100) NOT NULL,
    region       VARCHAR(50)  NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- customers: contains PII (national_id, phone, email, address)
-- -------------------------------------------------------------
CREATE TABLE customers (
    customer_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(100) NOT NULL,
    national_id    VARCHAR(12)  NOT NULL UNIQUE,          -- CCCD: 12 digits
    date_of_birth  DATE         NOT NULL,
    gender         CHAR(1)      NOT NULL CHECK (gender IN ('M', 'F')),
    phone          VARCHAR(15),
    email          VARCHAR(100),
    address        VARCHAR(255),
    branch_id      INT          NOT NULL REFERENCES branches (branch_id),
    segment        VARCHAR(20)  NOT NULL DEFAULT 'STANDARD'
                   CHECK (segment IN ('STANDARD', 'GOLD', 'PRIORITY')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TRIGGER trg_customers_updated_at
    BEFORE UPDATE ON customers
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -------------------------------------------------------------
-- accounts: balance is the CURRENT balance, updated with every transaction
-- -------------------------------------------------------------
CREATE TABLE accounts (
    account_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number  VARCHAR(20)   NOT NULL UNIQUE,
    customer_id     BIGINT        NOT NULL REFERENCES customers (customer_id),
    branch_id       INT           NOT NULL REFERENCES branches (branch_id),
    account_type    VARCHAR(10)   NOT NULL CHECK (account_type IN ('CURRENT', 'SAVINGS')),
    currency        CHAR(3)       NOT NULL DEFAULT 'VND',
    balance         NUMERIC(18,2) NOT NULL DEFAULT 0,
    status          VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    opened_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_accounts_customer ON accounts (customer_id);

CREATE TRIGGER trg_accounts_updated_at
    BEFORE UPDATE ON accounts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -------------------------------------------------------------
-- transactions: APPEND-ONLY ledger. Rows are never updated or deleted;
-- a mistake is corrected by a new reversing transaction.
-- -------------------------------------------------------------
CREATE TABLE transactions (
    transaction_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id            BIGINT        NOT NULL REFERENCES accounts (account_id),
    txn_type              VARCHAR(6)    NOT NULL CHECK (txn_type IN ('CREDIT', 'DEBIT')),
    amount                NUMERIC(18,2) NOT NULL CHECK (amount > 0),
    balance_after         NUMERIC(18,2) NOT NULL,
    channel               VARCHAR(10)   NOT NULL
                          CHECK (channel IN ('BRANCH', 'ATM', 'MOBILE', 'CARD', 'TRANSFER', 'SYSTEM')),
    counterparty_account  VARCHAR(34),
    description           VARCHAR(255),
    txn_time              TIMESTAMPTZ   NOT NULL,   -- when it happened (event time)
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now()  -- when it was recorded
);

CREATE INDEX idx_transactions_account_time ON transactions (account_id, txn_time);

-- -------------------------------------------------------------
-- loans
-- -------------------------------------------------------------
CREATE TABLE loans (
    loan_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT        NOT NULL REFERENCES accounts (account_id),
    principal_amount    NUMERIC(18,2) NOT NULL CHECK (principal_amount > 0),
    outstanding_amount  NUMERIC(18,2) NOT NULL CHECK (outstanding_amount >= 0),
    interest_rate       NUMERIC(5,2)  NOT NULL,   -- % per year
    term_months         INT           NOT NULL CHECK (term_months > 0),
    start_date          DATE          NOT NULL,
    days_past_due       INT           NOT NULL DEFAULT 0,
    status              VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE', 'PAID_OFF', 'OVERDUE', 'DEFAULT')),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_loans_account ON loans (account_id);

CREATE TRIGGER trg_loans_updated_at
    BEFORE UPDATE ON loans
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
